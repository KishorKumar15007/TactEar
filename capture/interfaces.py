from __future__ import annotations
from typing import Protocol, Callable
from tactear.types import AudioFrame, StereoAudioFrame, Orientation

class AmbientAudioSource(Protocol):
    def start(self) -> None: ...
    def stop(self) -> None: ...
    def read_frame(self, timeout: float = 1.0) -> StereoAudioFrame: ...
class BoomAudioSource(Protocol):
    def start(self) -> None: ...
    def stop(self) -> None: ...
    def read_frame(self, timeout: float = 1.0) -> AudioFrame: ...
class OrientationSensor(Protocol):
    def start(self) -> None: ...
    def stop(self) -> None: ...
    def read_orientation(self) -> Orientation: ...
class HapticOutput(Protocol):
    def trigger(self, pattern: str, direction: str = "front") -> None: ...
    def stop(self) -> None: ...
class ButtonInput(Protocol):
    def start(self, callback: Callable[[], None]) -> None: ...
    def stop(self) -> None: ...
